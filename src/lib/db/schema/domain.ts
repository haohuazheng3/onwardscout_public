/**
 * A real opportunity with its real URL. `search` is a generated, weighted full-text vector
 * (name A, organisation B, summary C, 'simple' config so any language tokenizes the same):
 * query it with `search @@ websearch_to_tsquery('simple', $q)`.
 */
export const opportunities = pgTable(
  "opportunities",
  {
    id: text("id").primaryKey(),
    type: text("type").$type<OpportunityTypeId>().notNull(),
    slug: text("slug").notNull(),
    name: text("name").notNull(),
    orgName: text("org_name"),
    orgSlug: text("org_slug"),
    url: text("url"),
    summary: text("summary"),
    description: text("description"),
    benefits: jsonb("benefits").$type<OpportunityBenefits>(),
    cost: jsonb("cost").$type<OpportunityCost>(),
    geo: jsonb("geo")
      .$type<OpportunityGeo>()
      .notNull()
      .default(sql`'{"countries":[],"cities":[],"remote":null,"worldwide":false}'::jsonb`),
    languages: text("languages").array().notNull().default(emptyTextArray),
    tags: text("tags").array().notNull().default(emptyTextArray),
    industries: text("industries").array().notNull().default(emptyTextArray),
    functions: text("functions").array().$type<FunctionId[]>().notNull().default(emptyTextArray),
    eligibility: jsonb("eligibility").$type<Eligibility>(),
    deadline: tsz("deadline"),
    rolling: boolean("rolling").notNull().default(false),
    /** "annual (spring)", "cohort W27"… */
    cycle: text("cycle"),
    apply: jsonb("apply").$type<ApplyInfo>().notNull(),
    requiredMaterials: text("required_materials").array().$type<MaterialId[]>().notNull().default(emptyTextArray),
    estAcceptanceRate: real("est_acceptance_rate"),
    estEffortMinutes: integer("est_effort_minutes"),
    /** 0–100. */
    qualityScore: integer("quality_score"),
    sourceId: text("source_id"),
    sourceRef: text("source_ref"),
    verifiedAt: tsz("verified_at"),
    status: text("status").$type<OpportunityStatus>().notNull().default("unverified"),
    public: boolean("public").notNull().default(false),
    search: tsvector("search").generatedAlwaysAs(
      sql`setweight(to_tsvector('simple', coalesce(name, '')), 'A') || setweight(to_tsvector('simple', coalesce(org_name, '')), 'B') || setweight(to_tsvector('simple', coalesce(summary, '')), 'C')`,
    ),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    uniqueIndex("opportunities_slug_uq").on(t.slug),
    uniqueIndex("opportunities_source_ref_uq").on(t.sourceId, t.sourceRef),
    index("opportunities_status_type_deadline_idx").on(t.status, t.type, t.deadline),
    index("opportunities_status_deadline_idx").on(t.status, t.deadline),
    index("opportunities_status_public_idx").on(t.status, t.public, t.updatedAt),
    index("opportunities_org_idx").on(t.orgSlug),
    index("opportunities_tags_gin").using("gin", t.tags),
    index("opportunities_industries_gin").using("gin", t.industries),
    index("opportunities_functions_gin").using("gin", t.functions),
    index("opportunities_search_gin").using("gin", t.search),
  ],
);

