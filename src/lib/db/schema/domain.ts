/*
 * Product tables (F2). Platform tables live in ./base.ts; ./index.ts re-exports both and is the
 * schema drizzle-kit reads. Conventions:
 * - ids are text from `newId(prefix)` (src/lib/ids.ts); user ids are the Clerk id as plain text
 *   (no FKs: Neon over HTTP has no interactive transactions, so every write is idempotent through
 *   unique keys + ON CONFLICT and conditional UPDATEs instead);
 * - every timestamp is timestamptz; every user-scoped query filters by `user_id`;
 * - jsonb columns are typed with the zod-backed types of src/lib/core/types.ts — validate with
 *   the matching schema before writing (and when reading data written by older code);
 * - honesty: unknown = NULL (shown as "check the official page"), never a guess.
 *
 * Only type imports from core here, so drizzle-kit never needs the `@/` alias.
 */
